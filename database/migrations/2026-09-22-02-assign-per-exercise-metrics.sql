-- 1. Tracking mode: 'sets' (sets x reps editor) vs 'single' (one value per metric).
UPDATE havit.exercises AS e
SET tracking_mode = p.tracking_mode::havit.tracking_mode_enum
FROM (
  SELECT DISTINCT ep.slug, mp.tracking_mode
  FROM tmp_exercise_profile ep
  JOIN tmp_metric_profile mp ON mp.profile = ep.profile
) AS p
WHERE e.source = 'repdb'
  AND e.source_id = p.slug
  AND e.content_locked = false
  AND e.tracking_mode IS DISTINCT FROM p.tracking_mode::havit.tracking_mode_enum;

-- 2. Metrics: replace whatever was there with the reviewed set.
DELETE FROM havit.exercise_metrics AS em
USING havit.exercises AS e, tmp_exercise_profile AS ep
WHERE em.exercise_id = e.id
  AND e.source = 'repdb'
  AND e.source_id = ep.slug;

INSERT INTO havit.exercise_metrics (exercise_id, metric_type_id, is_required, is_primary, default_unit)
SELECT e.id, mt.id, mp.is_required, mp.is_primary, mt.default_unit
FROM tmp_exercise_profile ep
JOIN tmp_metric_profile mp ON mp.profile = ep.profile
JOIN havit.exercises e ON e.source = 'repdb' AND e.source_id = ep.slug
JOIN havit.metric_types mt ON mt.code = mp.metric_code
ON CONFLICT (exercise_id, metric_type_id) DO UPDATE
  SET is_required = EXCLUDED.is_required,
      is_primary  = EXCLUDED.is_primary,
      default_unit = EXCLUDED.default_unit;
