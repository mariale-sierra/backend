-- 2026-09-22-02-assign-per-exercise-metrics.sql
--
-- Gives every RepDB-imported exercise its own reviewed tracking mode and metrics, instead of the
-- category-level guess. Source of truth: backend/src/exercises/lib/exercise-metric-profiles.ts (the
-- importer reads the same table; exercise-metric-profiles.spec.ts keeps this file in sync with it).
--
-- Why it matters beyond the wrong fields shown in the challenge builder: the importer never wrote
-- exercise_metrics rows for RepDB exercises, and MetricsService rejects every logged metric an exercise
-- has no exercise_metrics row for — so logging reps / time / distance against these exercises was
-- failing silently (best-effort writes, errors swallowed). This gives each one the rows it needs.
--
-- Scope / safety:
--   * Only source = 'repdb' exercises, matched by source_id (the RepDB slug).
--   * tracking_mode is left alone for content_locked rows, exactly like the importer.
--   * exercise_metrics for those exercises are REPLACED by the reviewed set (RepDB exercises had none).
--   * Idempotent: re-running converges to the same state. An id that does not exist in this database
--     simply matches nothing.

-- 0. The two metric types the rest of this file relies on. The live catalog already has 'time'
-- (seconds) and 'distance' (km) — the codes the whole app uses — so there this does nothing; a database
-- rebuilt from the repo's older seed only has 'duration'/'distanceKm', which nothing reads.
INSERT INTO havit.metric_types (code, name, value_type, default_unit, description) VALUES
  ('time', 'Duration', 'seconds', NULL, 'Duration of the exercise or set'),
  ('distance', 'Distance', 'decimal', 'km', 'Distance covered during the exercise')
ON CONFLICT (code) DO NOTHING;

